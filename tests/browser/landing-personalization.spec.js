const {test,expect}=require('@playwright/test');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'../..');

test('Contextual variants preserve defaults and preview safely in the native landing builder',async({page},testInfo)=>{
    const read=file=>fs.readFileSync(path.join(root,file),'utf8');
    await page.setContent(`<meta name="viewport" content="width=device-width,initial-scale=1"><style>body{margin:0;font:14px Arial}.form-control{width:100%;box-sizing:border-box}[hidden]{display:none!important}${read('espocrm/client/custom/css/landing-page-workspace.css')}</style>${read('espocrm/client/custom/res/templates/landing-page/workspace.tpl')}`);
    await page.evaluate(()=>{window.define=(name,deps,factory)=>{window.LandingView=factory(class {setPageTitle(){}},class {});};});
    await page.addScriptTag({content:read('espocrm/client/custom/src/views/landing-page/workspace.js')});
    await page.evaluate(()=>{
        const view=window.view=new LandingView();view.element=document.querySelector('.nexa-landing-workspace');view.setup();
        view.current={primaryColor:'#087d71',backgroundColor:'#ffffff',textColor:'#172f35',blocks:[{id:'hero-one',type:'hero',heading:'Default offer',text:'Default body'}]};
        view.selectedBlockId='hero-one';
        view.element.querySelector('[data-landing-list]').hidden=true;
        view.element.querySelector('[data-landing-editor]').hidden=false;
        view.settingsTab({currentTarget:view.element.querySelector('[data-settings-tab="block"]')});
        view.fillBlockSettings('hero-one');view.renderCanvas();
    });
    const controls=page.locator('[data-contextual-variant]');
    await expect(controls.getByRole('textbox',{name:'Matching value'})).toBeDisabled();
    await controls.getByRole('combobox',{name:'Match visitor context'}).selectOption('utm_source');
    await controls.getByRole('textbox',{name:'Matching value'}).fill('newsletter');
    await controls.getByRole('textbox',{name:'Variant heading'}).fill('Newsletter offer');
    await controls.getByRole('textbox',{name:'Variant body text'}).fill('Welcome newsletter readers');
    await expect(page.locator('[data-builder-canvas]')).toContainText('Default offer');
    await controls.getByRole('checkbox',{name:'Preview variant'}).check();
    await expect(page.locator('[data-builder-canvas]')).toContainText('Newsletter offer');
    await expect(page.locator('[data-builder-canvas] h1')).not.toHaveAttribute('contenteditable','true');
    expect(await page.evaluate(()=>view.current.blocks[0].heading)).toBe('Default offer');
    expect(await page.evaluate(()=>view.current.blocks[0].personalization)).toEqual({field:'utm_source',value:'newsletter',heading:'Newsletter offer',text:'Welcome newsletter readers'});
    const box=await controls.boundingBox();expect(box.x+box.width).toBeLessThanOrEqual(page.viewportSize().width+1);
    await page.screenshot({path:testInfo.outputPath('landing-variant.png'),fullPage:true});
    await controls.getByRole('combobox',{name:'Match visitor context'}).selectOption('');
    await expect(page.locator('[data-builder-canvas]')).toContainText('Default offer');
    expect(await page.evaluate(()=>Object.hasOwn(view.current.blocks[0],'personalization'))).toBe(false);
    await controls.getByRole('combobox',{name:'Match visitor context'}).selectOption('customer:leadScore');
    await controls.getByRole('combobox',{name:'Comparison',exact:true}).selectOption('greater_than');
    await controls.getByRole('textbox',{name:'Matching value'}).fill('50');
    expect(await page.evaluate(()=>view.current.blocks[0].personalization.operator)).toBe('greater_than');
    await controls.getByRole('combobox',{name:'Match visitor context'}).selectOption('customer:segment');
    await expect(controls.getByRole('combobox',{name:'Comparison',exact:true})).toBeHidden();
    await expect(controls.getByRole('textbox',{name:'Matching value'})).toBeHidden();
    await page.evaluate(()=>{view.createView=(name,type,options,callback)=>{window.audiencePickerOptions=options;callback({render(){}});};view.listenToOnce=(picker,event,callback)=>{if(event==='select')callback({id:'audience123',get:()=> 'Website subscribers'});};});
    await controls.getByRole('button',{name:'Choose audience'}).click();
    await expect(controls.getByRole('button',{name:'Website subscribers'})).toBeVisible();
    expect(await page.evaluate(()=>audiencePickerOptions.scope)).toBe('TargetList');
    expect(await page.evaluate(()=>view.current.blocks[0].personalization.value)).toBe('audience123');
    await page.evaluate(()=>{view.current.blocks.push({id:'form-one',type:'form'});view.selectedBlockId='form-one';view.variantSettings();});
    await expect(controls).toBeHidden();
});
