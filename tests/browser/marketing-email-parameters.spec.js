const {test,expect} = require('@playwright/test');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname,'../..');

test('Approved parameter insertion preserves drafts, limits and keyboard navigation', async ({page},testInfo) => {
    const template = fs.readFileSync(path.join(root,'espocrm/client/custom/res/templates/marketing-email/workspace.tpl'),'utf8');
    const css = fs.readFileSync(path.join(root,'espocrm/client/custom/css/marketing-email-workspace.css'),'utf8');
    await page.setContent(`<meta name="viewport" content="width=device-width,initial-scale=1"><style>body{margin:0;font:14px Arial}.form-control{box-sizing:border-box;width:100%}.btn{padding:8px}[hidden]{display:none!important}${css}</style>${template}`);
    await page.evaluate(() => {window.define = (name,deps,factory) => {window.MarketingView = factory(class {});};});
    await page.addScriptTag({content:fs.readFileSync(path.join(root,'espocrm/client/custom/src/views/marketing-email/workspace.js'),'utf8')});
    await page.evaluate(() => {
        window.Espo = {Ui:{error:message => {throw new Error(message);}}};
        const view = window.view = new MarketingView(); view.element = document.querySelector('main');
        view.contentEditorRequest = 1; view.once = () => {};
        const editor = view.element.querySelector('[data-email-editor]'); editor.hidden = false; editor.style.display = 'grid';
        view.element.querySelector('[name="bodyHtml"]').value = '<p>Original {Contact.firstName}</p>';
        view.element.querySelector('[name="subject"]').value = 'Appointment';
        view.renderContentPreview();
        view.element.addEventListener('click', event => {
            const button = event.target.closest('button');
            if (button?.dataset.action === 'insert-parameter') view.openParameterDialog({currentTarget:button});
            if (button?.dataset.action === 'close-parameter') view.closeParameterDialog();
        });
        view.element.addEventListener('submit', event => {if (event.target.matches('[data-parameter-form]')) view.insertParameter(event);});
    });
    const launch = page.getByRole('button',{name:'Insert parameter',exact:true});
    const dialog = page.getByRole('dialog',{name:'Insert parameter',exact:true});
    await launch.click();
    await expect(dialog.getByRole('textbox',{name:'Parameter name'})).toBeFocused();
    await dialog.getByRole('textbox',{name:'Parameter name'}).fill('appointment_reference');
    await dialog.getByRole('button',{name:'Cancel',exact:true}).click();
    await expect(page.locator('[name="bodyHtml"]')).toHaveValue('<p>Original {Contact.firstName}</p>');
    await expect(launch).toBeFocused();
    await launch.click();
    await dialog.getByRole('textbox',{name:'Parameter name'}).fill('appointment_reference');
    await dialog.getByRole('button',{name:'Insert',exact:true}).focus();
    await page.keyboard.press('Tab'); await expect(dialog.getByRole('button',{name:'Close parameter',exact:true})).toBeFocused();
    await page.keyboard.press('Shift+Tab'); await expect(dialog.getByRole('button',{name:'Insert',exact:true})).toBeFocused();
    await testInfo.attach('email-parameters.png',{body:await page.screenshot({path:path.join(root,`test-results/email-parameters-${testInfo.project.name}.png`)}),contentType:'image/png'});
    const bounds = await dialog.boundingBox();
    expect(bounds.x).toBeGreaterThanOrEqual(0); expect(bounds.x + bounds.width).toBeLessThanOrEqual(page.viewportSize().width + 1);
    expect(bounds.height).toBeLessThanOrEqual(page.viewportSize().height);
    await dialog.getByRole('button',{name:'Insert',exact:true}).click();
    await expect(dialog).toHaveCount(0);
    await expect(page.locator('[name="bodyHtml"]')).toHaveValue('<p>Original {Contact.firstName}</p><p>[[nexa:appointment_reference:40]]</p>');
    await launch.click();
    await dialog.getByRole('textbox',{name:'Parameter name'}).fill('appointment_reference');
    await dialog.getByRole('spinbutton',{name:'Maximum characters'}).fill('80');
    await dialog.getByRole('button',{name:'Insert',exact:true}).click();
    await expect(dialog.getByRole('alert')).toHaveText('This parameter already uses a different character limit.');
    await dialog.getByRole('spinbutton',{name:'Maximum characters'}).fill('40');
    await dialog.getByRole('combobox',{name:'Insert into'}).selectOption('subject');
    await dialog.getByRole('button',{name:'Insert',exact:true}).click();
    await expect(page.locator('[name="subject"]')).toHaveValue('Appointment [[nexa:appointment_reference:40]]');
    await launch.click();
    await dialog.getByRole('textbox',{name:'Parameter name'}).fill('appointment_reference');
    await dialog.getByRole('combobox',{name:'Insert into'}).selectOption('preheader');
    await dialog.getByRole('button',{name:'Insert',exact:true}).click();
    await expect(page.locator('[name="preheader"]')).toHaveValue('[[nexa:appointment_reference:40]]');
    await page.evaluate(() => {document.querySelector('[name="subject"]').value = 'x'.repeat(250);});
    await launch.click();
    await dialog.getByRole('textbox',{name:'Parameter name'}).fill('another');
    await dialog.getByRole('combobox',{name:'Insert into'}).selectOption('subject');
    await dialog.getByRole('button',{name:'Insert',exact:true}).click();
    await expect(dialog.getByRole('alert')).toContainText('too long');
    await dialog.press('Escape'); await expect(dialog).toHaveCount(0);
    await page.evaluate(() => {document.querySelector('[name="bodyHtml"]').value = Array.from({length:20},(_,i) => `<p>[[nexa:p${i}:40]]</p>`).join('');});
    await launch.click(); await dialog.getByRole('textbox',{name:'Parameter name'}).fill('another');
    await dialog.getByRole('button',{name:'Insert',exact:true}).click();
    await expect(dialog.getByRole('alert')).toHaveText('This email already has 20 parameters.');
    await dialog.getByRole('button',{name:'Cancel',exact:true}).click();
    await launch.click(); await dialog.getByRole('textbox',{name:'Parameter name'}).fill('stale');
    await page.evaluate(() => {view.contentEditorRequest++;});
    const previous = await page.locator('[name="bodyHtml"]').inputValue();
    await dialog.getByRole('button',{name:'Insert',exact:true}).click();
    await expect(dialog).toHaveCount(0); await expect(page.locator('[name="bodyHtml"]')).toHaveValue(previous);
});

test('Parameter values render in the sandbox without changing the draft and cancel stale responses', async ({page},testInfo) => {
    const template = fs.readFileSync(path.join(root,'espocrm/client/custom/res/templates/marketing-email/workspace.tpl'),'utf8');
    const css = fs.readFileSync(path.join(root,'espocrm/client/custom/css/marketing-email-workspace.css'),'utf8');
    await page.setContent(`<meta name="viewport" content="width=device-width,initial-scale=1"><style>body{margin:0;font:14px Arial}.form-control{box-sizing:border-box;width:100%}.btn{padding:8px}[hidden]{display:none!important}${css}</style>${template}`);
    await page.evaluate(() => {window.define = (name,deps,factory) => {window.MarketingView = factory(class {});};});
    await page.addScriptTag({content:fs.readFileSync(path.join(root,'espocrm/client/custom/src/views/marketing-email/workspace.js'),'utf8')});
    await page.evaluate(() => {
        window.requests = []; window.model = {id:'contact-fixture',get:()=>'Preview Customer'};
        window.Espo = {Ui:{notify:()=>{},error:message=>{throw new Error(message);}},Ajax:{postRequest:async (url,input)=>{
            requests.push({url,input});
            if (window.rejectPreview) throw new Error('Parameter value is invalid.');
            const result = {subject:'Reference APPT-42',bodyHtml:'<p>Confirmed Preview</p>',preheader:'APPT-42 Customer'};
            if (window.deferPreview) return new Promise(resolve=>{window.finishPreview=()=>resolve(result);});
            return result;
        }}};
        const view = window.view = new MarketingView(); view.element = document.querySelector('main'); view.contentEditorRequest=1; view.once=()=>{};
        const editor = view.element.querySelector('[data-email-editor]'); editor.hidden=false; editor.style.display='grid';
        const form = view.element.querySelector('[data-email-form]');
        form.elements.subject.value='Reference [[nexa:reference:40]]'; form.elements.preheader.value='[[nexa:reference:40]] {Contact.lastName}'; form.elements.bodyHtml.value='<p>{Contact.firstName}</p>';
        view.renderContentPreview();
        view.element.addEventListener('click',event=>{
            const action=event.target.closest('[data-action]')?.dataset.action;
            if(action==='preview-contact') view.previewContact(model);
            if(action==='close-parameter-preview') view.closeParameterPreview();
        });
        view.element.addEventListener('submit',event=>{if(event.target.matches('[data-parameter-preview-form]')) view.submitParameterPreview(event);});
    });
    const launch=page.getByRole('button',{name:'Preview as Contact',exact:true});
    const dialog=page.getByRole('dialog',{name:'Preview parameters',exact:true});
    await launch.click(); await expect(dialog.getByRole('textbox',{name:'reference'})).toBeFocused();
    await expect(dialog.getByRole('textbox')).toHaveCount(1);
    await dialog.press('Escape'); await expect(dialog).toHaveCount(0); expect(await page.evaluate(()=>requests.length)).toBe(0);
    await launch.click(); await dialog.getByRole('textbox',{name:'reference'}).fill('APPT-42');
    await testInfo.attach('parameter-preview.png',{body:await page.screenshot({path:path.join(root,`test-results/parameter-preview-${testInfo.project.name}.png`)}),contentType:'image/png'});
    await page.evaluate(()=>{window.rejectPreview=true;});
    await dialog.getByRole('button',{name:'Preview',exact:true}).click(); await expect(dialog.getByRole('alert')).toHaveText('Parameter value is invalid.');
    await expect(dialog.getByRole('textbox',{name:'reference'})).toBeEnabled();
    await page.evaluate(()=>{window.rejectPreview=false;});
    await dialog.getByRole('button',{name:'Preview',exact:true}).click(); await expect(dialog).toHaveCount(0);
    await expect(page.locator('[data-preview-subject]')).toHaveText('Reference APPT-42'); await expect(page.locator('[data-preview-preheader]')).toHaveText('APPT-42 Customer');
    await expect(page.locator('[name="subject"]')).toHaveValue('Reference [[nexa:reference:40]]');
    expect(await page.evaluate(()=>requests[0].input.parameters)).toEqual({reference:'APPT-42'});
    await launch.click(); await dialog.getByRole('textbox',{name:'reference'}).fill('APPT-42');
    await page.evaluate(()=>{window.deferPreview=true;});
    await dialog.getByRole('button',{name:'Preview',exact:true}).click();
    await expect(dialog.getByRole('textbox',{name:'reference'})).toBeDisabled();
    await dialog.getByRole('button',{name:'Cancel',exact:true}).click();
    await page.evaluate(()=>{view.recipientPreview=null; window.finishPreview();});
    await expect.poll(()=>page.evaluate(()=>view.recipientPreview)).toBeNull();
    await launch.click(); await dialog.getByRole('textbox',{name:'reference'}).fill('APPT-42');
    await page.evaluate(()=>{document.querySelector('[name="preheader"]').value='Changed draft';});
    await dialog.getByRole('button',{name:'Preview',exact:true}).click(); await expect(dialog.getByRole('alert')).toContainText('draft changed');
});
